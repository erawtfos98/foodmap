#!/usr/bin/env node
// Builds both pages from src/template.html:
//   index.html                  the repo/GitHub Pages version: OpenStreetMap tiles, vendored Leaflet,
//                               YouTube thumbnails loaded from YouTube when no saved copy exists.
//   dist/foodies-table-map.html the self-contained version for hosts that block outside images and tiles
//                               (a claude.ai artifact): drawn coastline, saved thumbnails only.
// Usage: node scripts/build.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');

const tpl = read('src/template.html');
const split = tpl.indexOf('<aside');
const head = tpl.slice(0, split), body = tpl.slice(split);

const thumbs = fs.existsSync(path.join(root, 'thumbs'))
  ? fs.readdirSync(path.join(root, 'thumbs')).filter(f => f.endsWith('.jpg')).map(f => f.slice(0, -4)).sort()
  : [];
fs.writeFileSync(path.join(root, 'data/thumbs.js'),
  '// Generated by scripts/build.js: thumbnails present in thumbs/.\nwindow.THUMBS = ' + JSON.stringify(thumbs) + ';\n');

// Sanity check the data before building.
const ctx = { window: {} };
vm.runInNewContext(read('data/places.js'), ctx);
const places = ctx.window.PLACES;
places.forEach(p => {
  if (typeof p.lat !== 'number' || typeof p.lng !== 'number' || !p.videos || !p.videos.length) {
    throw new Error('Incomplete place: ' + p.name);
  }
});

// Repo version
const repoHead = head.replace('<!--HEAD-->', '<link rel="stylesheet" href="vendor/leaflet/leaflet.css">');
const repoScripts = [
  '<script src="vendor/leaflet/leaflet.js"></script>',
  '<script src="data/places.js"></script>',
  '<script src="data/thumbs.js"></script>',
  '<script>window.MAP_CONFIG = { tiles: true, remoteYouTubeThumbs: true };</script>'
].join('\n');
fs.writeFileSync(path.join(root, 'index.html'),
  '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1">\n' +
  '<!-- Generated by scripts/build.js from src/template.html. Edit the template, not this file. -->\n' +
  repoHead + '</head>\n<body>\n' + body.replace('<!--SCRIPTS-->', repoScripts) + '</body>\n</html>\n');

// Self-contained version
const leafletCss = read('vendor/leaflet/leaflet.css').replace(/url\([^)]*\)/g, 'none');
const inline = s => s.replace(/<\/script/gi, '<\\/script');
const distScripts = [
  '<script src="https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.min.js"></script>',
  '<script>',
  inline(read('data/places.js')),
  'window.THUMBS = ' + JSON.stringify(thumbs) + ';',
  'window.LAND = ' + read('data/land.json') + ';',
  'window.MAP_CONFIG = { tiles: false };',
  '</script>'
].join('\n');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/foodies-table-map.html'),
  head.replace('<!--HEAD-->', '<style>' + leafletCss + '</style>') + body.replace('<!--SCRIPTS-->', () => distScripts));

console.log(places.length + ' places, ' + ctx.window.UNMAPPED.length + ' unmapped videos, ' + thumbs.length + ' thumbnails');
